# train_yolo2pos.py
# 功能：微调 DeepSeek-R1-Distill-Qwen-14B，让它学会 YOLO txt -> POS 表

from datasets import Dataset
import pandas as pd
from transformers import (
    AutoTokenizer,
    AutoModelForCausalLM,
    DataCollatorForSeq2Seq,
    TrainingArguments,
    Trainer,
    GenerationConfig,
)
from peft import LoraConfig, TaskType, get_peft_model
import torch

# ========== 1. 路径 & 基本配置 ==========

base_model_path = r""

# 用你刚生成的 YOLO->POS 数据集
DATA_PATH = r""  #数据集

OUTPUT_DIR = r""  #输出目录

# ========== 2. 加载基座模型 ==========

model = AutoModelForCausalLM.from_pretrained(
    base_model_path,
    trust_remote_code=True,
    torch_dtype=torch.half,
    device_map="auto",
)

print("=== debug devices ===")
first_param = next(model.parameters())
print("First param device:", first_param.device)
print("=====================")

model.generation_config = GenerationConfig.from_pretrained(base_model_path)
model.generation_config.pad_token_id = model.generation_config.eos_token_id
model.enable_input_require_grads()  # 开启梯度检查点时，需要这一句

# ========== 3. 加载数据集 & 划分 train / eval ==========

print("===> loading ...")
df = pd.read_json(DATA_PATH)
full_ds = Dataset.from_pandas(df)
print("data num:", len(full_ds))

split_ds = full_ds.train_test_split(test_size=0.2, seed=42)
train_ds = split_ds["train"]
eval_ds = split_ds["test"]
print("Tdata num:", len(train_ds))
print("Vdata num:", len(eval_ds))

# ========== 4. tokenizer & SYSTEM_PROMPT（只做 POS） ==========

tokenizer = AutoTokenizer.from_pretrained(
    base_model_path,
    use_fast=False,
    trust_remote_code=True,
)
tokenizer.padding_side = "right"
if tokenizer.pad_token_id is None:
    tokenizer.pad_token_id = tokenizer.eos_token_id

SYSTEM_PROMPT = (
    "You are an expert in manufacturing system simulation modeling. Your task is to transform equipment detection results obtained from CAD drawings into structured object parameters required for simulation model construction. The input information is generated by the YOLOv12 object detection model and represented using normalized bounding box coordinates. Based on the provided detection results, perform equipment category mapping, coordinate transformation, dimension estimation, and simulation entity naming. The following requirements must be satisfied: 1. The number of generated simulation entities must exactly match the number of detected objects; 2. No detected objects may be omitted, duplicated, or artificially added; 3. The output format must strictly follow: name, x, y, width, height; 4. Only structured equipment parameter information is allowed in the output, without any additional explanations."
)


def process_func(example):
    # 可以根据显存情况调整最大长度
    MAX_LENGTH = 2048

    # instruction + input 合并成用户输入（中间加一个空行更清晰）
    user_text = (example.get("instruction", "") or "") + "\n\n" + (
        example.get("input", "") or ""
    )
    assistant_text = example.get("output", "") or ""

    # DeepSeek / Qwen 通用 chat 模板
    prompt = (
        f"<|im_start|>system\n{SYSTEM_PROMPT}<|im_end|>\n"
        f"<|im_start|>user\n{user_text}<|im_end|>\n"
        f"<|im_start|>assistant\n"
    )

    # 分别对 prompt（不含回答）和回答做分词
    instruction = tokenizer(
        prompt,
        add_special_tokens=False,
    )
    response = tokenizer(
        assistant_text,
        add_special_tokens=False,
    )

    input_ids = instruction["input_ids"] + response["input_ids"] + [
        tokenizer.eos_token_id
    ]
    attention_mask = instruction["attention_mask"] + response["attention_mask"] + [1]

    # labels：system+user 部分设为 -100，只训练 assistant 的输出
    labels = [-100] * len(instruction["input_ids"]) + response["input_ids"] + [
        tokenizer.eos_token_id
    ]

    # 截断
    if len(input_ids) > MAX_LENGTH:
        input_ids = input_ids[:MAX_LENGTH]
        attention_mask = attention_mask[:MAX_LENGTH]
        labels = labels[:MAX_LENGTH]

    return {
        "input_ids": input_ids,
        "attention_mask": attention_mask,
        "labels": labels,
    }


print("===> tokening  ...")
tokenized_train_ds = train_ds.map(process_func, remove_columns=train_ds.column_names)
tokenized_eval_ds = eval_ds.map(process_func, remove_columns=eval_ds.column_names)
print("Token finish：", len(tokenized_train_ds[0]["input_ids"]))

# ========== 5. 配置 LoRA ==========
print("===>  LoRA ...")
lora_config = LoraConfig(
    task_type=TaskType.CAUSAL_LM,
    target_modules=[
        "q_proj",
        "k_proj",
        "v_proj",
        "o_proj",
        "gate_proj",
        "up_proj",
        "down_proj",
    ],
    inference_mode=False,  # 训练模式
    r=8,
    lora_alpha=32,
    lora_dropout=0.1,
)

model = get_peft_model(model, lora_config)
model.print_trainable_parameters()

# ========== 6. TrainingArguments & Trainer ==========

print("===>  TrainingArguments ...")
training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,
    per_device_train_batch_size=1,
    per_device_eval_batch_size=1,  # eval 小一点防止 OOM
    gradient_accumulation_steps=8,
    gradient_checkpointing=True,
    eval_strategy="steps",
    eval_steps=5,
save_steps=5,
    num_train_epochs=5,
    learning_rate=2e-5,
    weight_decay=0.01,
    warmup_ratio=0.1,

    logging_steps=5,
    save_strategy="steps",
    save_total_limit=2,
    save_on_each_node=True,

)

data_collator = DataCollatorForSeq2Seq(
    tokenizer=tokenizer,
    padding=True,
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_train_ds,
    eval_dataset=tokenized_eval_ds,
    data_collator=data_collator,
)

# ========== 7. 开始训练 ==========

if __name__ == "__main__":
    trainer.train()
    # 如果评估时显存不够，可以单独写 eval 脚本，这里就不强制 evaluate()
    eval_result = trainer.evaluate()
    print("Eval result:", eval_result)

    trainer.save_model(OUTPUT_DIR)
    tokenizer.save_pretrained(OUTPUT_DIR)
